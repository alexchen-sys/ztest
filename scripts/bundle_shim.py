#!/usr/bin/env python3
"""Deterministic bundler for the ztest shim (ADR-006 v2).

The shim ships as ONE file embedded into the native binary via
``@embedFile("shim/ztest_shim.py")``; the single-binary delivery and the zero
runtime import overhead are unchanged from v0.5.x. What changed is the source
layout: ``src/shim/modules/*.py`` holds clean, logically scoped source modules
and this script concatenates them, in a fixed order, into the bundle.

Design rules (red lines):
  * No runtime import/exec machinery between modules: every module shares the
    single ``__main__`` namespace of the extracted shim, exactly as the v0.5.x
    monolith did. Module docstrings document provided/required names.
  * Deterministic: fixed MODULE_ORDER, LF newlines, a fixed generated header
    and trailer. Re-running the bundler on unchanged modules is byte-stable.
  * ``--check`` is the CI freshness gate: it fails (rc=1, diff on stderr) when
    the committed bundle is not what the modules generate.

Usage:
    python3 scripts/bundle_shim.py            # regenerate src/shim/ztest_shim.py
    python3 scripts/bundle_shim.py --check    # CI: fail if stale
    python3 scripts/bundle_shim.py --stdout   # print the bundle (proof tooling)
    python3 scripts/bundle_shim.py --list     # module order and sizes
"""
from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MODULES_DIR = REPO_ROOT / "src" / "shim" / "modules"
BUNDLE = REPO_ROOT / "src" / "shim" / "ztest_shim.py"

# Fixed order = definition order of the v0.5.x monolith. It is load-bearing:
# later sections reference names defined by earlier ones at import time.
MODULE_ORDER = [
    "00_header",
    "10_ipc_protocol",
    "20_outcomes",
    "30_marks_and_helpers",
    "40_builtin_fixtures",
    "50_ast_rewrite",
    "60_fixture_engine",
    "70_pytest_stubs",
    "80_collection",
    "82_execution_engine",
    "84_runner_core",
    "85_pytest_engine",
    "86_runner_file",
    "87_failure_report",
    "90_zygote",
]

GENERATED_HEADER = (
    "#!/usr/bin/env python3\n"
    "# GENERATED by scripts/bundle_shim.py - DO NOT EDIT THIS FILE DIRECTLY.\n"
    "# Source of truth: src/shim/modules/*.py (ADR-006 v2).\n"
    "# Regenerate: python3 scripts/bundle_shim.py ; freshness: --check\n"
)
GENERATED_TRAILER = "# end of generated ztest shim bundle\n"


def module_path(name: str) -> Path:
    return MODULES_DIR / f"{name}.py"


def generate() -> str:
    """Return the deterministic bundle text for the current module sources."""
    parts: list[str] = [GENERATED_HEADER]
    for name in MODULE_ORDER:
        path = module_path(name)
        if not path.is_file():
            raise SystemExit(f"bundle_shim: missing module {path}")
        text = path.read_text(encoding="utf-8")
        if text.startswith("#!"):
            # Only the generated header carries a shebang.
            text = text.split("\n", 1)[1] if "\n" in text else ""
        if not text.endswith("\n"):
            text += "\n"
        parts.append(text)
    parts.append(GENERATED_TRAILER)
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if the committed bundle is stale")
    mode.add_argument("--stdout", action="store_true", help="write the bundle to stdout")
    mode.add_argument("--list", action="store_true", help="list module order and sizes")
    args = parser.parse_args(argv)

    if args.list:
        for name in MODULE_ORDER:
            path = module_path(name)
            print(f"{name}: {path.stat().st_size} bytes")
        print(f"total modules: {len(MODULE_ORDER)}")
        return 0

    bundle = generate()
    if args.stdout:
        sys.stdout.write(bundle)
        return 0
    if args.check:
        current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.is_file() else ""
        if current == bundle:
            print(f"bundle_shim: {BUNDLE.relative_to(REPO_ROOT)} is up to date ({len(bundle)} bytes)")
            return 0
        diff = difflib.unified_diff(
            current.splitlines(), bundle.splitlines(),
            fromfile="committed bundle", tofile="generated bundle", lineterm="",
        )
        sys.stderr.write("bundle_shim: STALE bundle; run python3 scripts/bundle_shim.py\n")
        for i, line in enumerate(diff):
            if i >= 60:
                sys.stderr.write("... (diff truncated)\n")
                break
            sys.stderr.write(line + "\n")
        return 1
    BUNDLE.write_text(bundle, encoding="utf-8")
    print(f"bundle_shim: wrote {BUNDLE.relative_to(REPO_ROOT)} ({len(bundle)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
